import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { realpathSync } from 'node:fs';
import { join } from 'node:path';
import { createServer } from 'vite';
const pw = createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE || 'playwright');
const engine = process.env.BROWSER_ENGINE || 'chromium';
const root = fileURLToPath(new URL('..', import.meta.url));
const server = await createServer({root, server:{host:'127.0.0.1',port:0,watch:null,hmr:false,fs:{allow:[root,realpathSync(join(root,'node_modules'))]}},logLevel:'error'});
let browser;
try {
  await server.listen();
  browser = await pw[engine].launch({headless:true,...(engine==='chromium'?{executablePath:process.env.BROWSER_EXECUTABLE||undefined}:{})});
  const page = await browser.newPage({viewport:{width:1366,height:768}});
  page.setDefaultTimeout(10000);
  await page.addInitScript(()=>{localStorage.setItem('spellcheckEnabled','false');localStorage.setItem('spellcheckPersonalWords',JSON.stringify(['quillitetest']));});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/*',r=>new URL(r.request().url()).hostname==='127.0.0.1'?r.continue():r.abort());
  await page.goto(server.resolvedUrls.local[0]);
  await page.waitForFunction(()=>window.quilliteMarkdown);
  await page.waitForFunction(()=>document.querySelector('[data-spellcheck-toggle]')?.getAttribute('aria-checked')==='false');
  const panel=page.locator('#spellingSettingsMenu'), trigger=page.locator('[data-settings-submenu="spelling"]');
  const open=async()=>{if(!await page.locator('#moreMenu').isVisible())await page.locator('#moreButton').click();await trigger.click();await panel.waitFor({state:'visible'});};
  await open();
  assert.equal(await panel.locator('[data-spellcheck-toggle]').count(),1);
  assert.equal(await panel.locator('select').count(),0);
  assert.equal(await panel.locator('[data-spellcheck-language]').count(),3);
  assert.equal(await panel.locator('[data-spellcheck-clear]').count(),1);
  assert.equal(await page.locator('#moreMenu [data-action="export-center"], #moreMenu [data-action="print"]').count(),0);
  assert.equal(await page.locator('#moreMenu [data-action="document-tools"]').count(),1);
  for (const language of ['en-US','auto','en-GB']) {
    await panel.locator(`[data-spellcheck-language="${language}"]`).press('Enter');
    assert.equal(await page.evaluate(()=>localStorage.getItem('spellcheckLanguage')),language);
    await open();
    assert.equal(await panel.locator('[data-spellcheck-language][aria-checked="true"]').count(),1);
    assert.equal(await panel.locator('[data-spellcheck-language][aria-checked="true"]').getAttribute('data-spellcheck-language'),language);
  }
  page.once('dialog',d=>d.dismiss());await panel.locator('[data-spellcheck-clear]').click();
  assert.equal(await page.evaluate(()=>JSON.parse(localStorage.getItem('spellcheckPersonalWords')).length),1);
  await open();page.once('dialog',d=>d.accept());await panel.locator('[data-spellcheck-clear]').click();
  assert.equal(await page.evaluate(()=>localStorage.getItem('spellcheckPersonalWords')),'[]');
  await open();await panel.locator('[data-spellcheck-toggle]').click();
  assert.equal(await page.evaluate(()=>localStorage.getItem('spellcheckEnabled')),'true');
  await open();await panel.locator('[data-spellcheck-toggle]').click();
  assert.equal(await page.evaluate(()=>localStorage.getItem('spellcheckEnabled')),'false');
  await open();await panel.locator('[data-spellcheck-toggle]').press('Escape');
  assert.equal(await panel.isVisible(),false);
  await trigger.press('ArrowRight');await page.waitForTimeout(80);
  assert.equal(await panel.locator('[data-spellcheck-language="en-GB"]').evaluate(el=>el===document.activeElement),true,'keyboard entry focuses the selected dictionary when spellcheck is disabled');
  const bounds=await panel.boundingBox();assert.ok(bounds.x>=0&&bounds.y>=0&&bounds.x+bounds.width<=1366&&bounds.y+bounds.height<=768);
  if(process.env.AUDIT_OUTPUT)await page.screenshot({path:join(process.env.AUDIT_OUTPUT,`spelling-menu-${engine}-zh.png`)});
  await page.keyboard.press('Escape');await page.locator('[data-settings-submenu="language"]').click();await page.locator('[data-language="en"]').click();
  await page.setViewportSize({width:1024,height:640});await page.locator('#colorModeButton').click();await open();
  assert.equal(await trigger.innerText(),'Spell check');
  assert.equal(await panel.locator('[data-spellcheck-language="en-GB"]').getAttribute('aria-checked'),'true');
  const small=await panel.boundingBox();assert.ok(small.x>=0&&small.y>=0&&small.x+small.width<=1024&&small.y+small.height<=640);
  await page.locator('#toast').waitFor({state:'hidden'});
  if(process.env.AUDIT_OUTPUT)await page.screenshot({path:join(process.env.AUDIT_OUTPUT,`spelling-menu-${engine}-en-dark.png`)});
  await page.mouse.click(10,150);assert.equal(await panel.isVisible(),false);
  await page.evaluate(()=>{window.quilliteMarkdown.openFile=async()=>({path:'/menu-test.md',directory:'/',name:'menu-test.md',content:'# Menu test\n\nHello world.',revision:'a'.repeat(64)});window.printCalls=0;window.quilliteMarkdown.print=async()=>{window.printCalls++;};});
  await page.locator('#openFileButton').click();await page.locator('#markdownContent h1').waitFor();
  await page.setViewportSize({width:1440,height:900});
  await page.locator('#documentExportButton').click();await page.locator('#exportCenterDialog').waitFor({state:'visible'});await page.keyboard.press('Escape');
  await page.locator('#printButton').click();await page.waitForFunction(()=>window.printCalls===1);
  await page.keyboard.press('Control+p');await page.waitForFunction(()=>window.printCalls===2);
  assert.deepEqual(errors,[]);
  console.log('PASS',engine,'spelling grouping, dictionary/toggle/clear, keyboard, viewport bounds, bilingual themes, retained export/print');
} finally {await browser?.close();await server.close();}
