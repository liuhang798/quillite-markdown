import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import {createServer} from 'vite';
const {chromium}=createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE||'playwright');
const server=await createServer({root:fileURLToPath(new URL('..',import.meta.url)),server:{host:'127.0.0.1',port:0,watch:null,hmr:false},logLevel:'error'});
let browser;
try {
  await server.listen();
  browser=await chromium.launch({headless:true,executablePath:process.env.BROWSER_EXECUTABLE||undefined});
  const page=await browser.newPage({viewport:{width:1450,height:850}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/*',r=>new URL(r.request().url()).hostname==='127.0.0.1'?r.continue():r.abort());
  await page.goto(server.resolvedUrls.local[0]+'tests/fixtures/multiline-edit-audit.html');
  const frame=page.frames().find(f=>f.parentFrame());
  await frame.evaluate(async()=>{await import('/src/main.js');});
  const app=page.frameLocator('iframe');
  await app.locator('#newFileButton').click();
  await app.locator('#hideLivePreviewButton').click();
  const select=app.locator('#headingSelect'),control=app.locator('.heading-style-control');
  assert.equal(await select.getAttribute('aria-label'),'文字样式（正文／标题）');
  const ai=await app.locator('#aiToolbarButton').boundingBox(),style=await control.boundingBox();
  assert.ok(style.x>=ai.x+ai.width&&style.x<ai.x+ai.width+25);
  assert.equal(await select.locator('option').count(),7);
  await app.locator('[data-editor-presentation="source"]').click();
  const content=app.locator('#markdownEditor > .cm-editor > .cm-scroller > .cm-content');
  await content.fill('Sample');await content.press('Control+Home');
  const icon=await app.locator('.heading-style-icon').boundingBox();
  assert.equal(icon.height,16);assert.ok(Math.abs(icon.y+icon.height/2-(ai.y+ai.height/2))<1);
  await select.click();
  const menu=app.locator('#textStyleMenu');await menu.waitFor({state:'visible'});
  assert.ok((await menu.boundingBox()).width>=136);
  assert.equal(await menu.locator('button').count(),7);
  assert.equal(await menu.locator('button').first().evaluate(el=>getComputedStyle(el).textAlign),'center');
  if(process.env.AUDIT_OUTPUT)await page.screenshot({path:process.env.AUDIT_OUTPUT+'/text-style-menu-light.png'});
  await page.keyboard.press('ArrowDown');await page.keyboard.press('Enter');
  assert.equal((await content.innerText()).trim(),'# Sample');
  await page.keyboard.press('Control+z');assert.equal((await content.innerText()).trim(),'Sample');
  await app.locator('#aiToolbarButton').focus();await page.keyboard.press('Tab');
  assert.equal(await select.evaluate(el=>el===document.activeElement),true);
  if(process.env.AUDIT_OUTPUT)await page.screenshot({path:process.env.AUDIT_OUTPUT+'/text-style-light.png'});
  // Force the existing responsive overflow path without changing application state.
  await app.locator('#editorFormatBar').evaluate(el=>el.style.width='175px');
  await control.waitFor({state:'hidden'});
  await app.locator('#moreFormatButton').click();
  assert.equal(await app.locator('#overflowFormatOptions [data-format-command^="heading:"]').count(),7);
  await app.locator('#overflowFormatOptions [data-format-command="heading:## "]').click();
  assert.equal((await content.innerText()).trim(),'## Sample');
  await app.locator('#editorFormatBar').evaluate(el=>el.style.removeProperty('width'));
  await control.waitFor({state:'visible'});
  await select.click();await menu.locator('button').first().click();
  assert.equal((await content.innerText()).trim(),'Sample','Paragraph command works even when select was reset');
  await select.click();await page.keyboard.press('Escape');
  assert.equal(await menu.isVisible(),false);assert.equal(await select.evaluate(el=>el===document.activeElement),true);
  await page.keyboard.press('Enter');await app.locator('#aiToolbarButton').click();
  assert.equal(await menu.isVisible(),false);await page.keyboard.press('Escape');
  await app.locator('#moreButton').click();
  await app.locator('[data-settings-submenu="language"]').click();
  await app.locator('[data-language="en"]').click();
  assert.equal(await select.getAttribute('aria-label'),'Text style (paragraph / headings)');
  await app.locator('#colorModeButton').click();
  await select.click();await menu.waitFor({state:'visible'});
  assert.equal(await menu.locator('button').nth(1).innerText(),'Heading 1');
  const colors=await control.evaluate(el=>({icon:getComputedStyle(el).color,text:getComputedStyle(document.body).getPropertyValue('--text').trim()}));
  assert.ok(colors.icon&&colors.text);
  if(process.env.AUDIT_OUTPUT)await page.screenshot({path:process.env.AUDIT_OUTPUT+'/text-style-dark.png'});
  assert.deepEqual(errors,[]);
  console.log('PASS: centered 16px icon, independent centered menu, pointer/keyboard headings, undo, Tab focus, 7 overflow commands, paragraph, dismissal, bilingual themes');
} finally {await browser?.close();await server.close();}
