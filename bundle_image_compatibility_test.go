func TestBundleImageCompatibilityFallbackRejectsNonImageBytes(t *testing.T) {
	for _, payload := range []string{"ordinary attachment text", `<html><script>alert(1)</script></html>`, `<?xml version="1.0"?><html xmlns="http://www.w3.org/1999/xhtml"/>`, `<!DOCTYPE svg [<!ENTITY file SYSTEM "file:///secret">]><svg>&file;</svg>`} {
		app := bundleIntegrationApp(t)
		name := filepath.Join(textPackTestDirectory(t), "Attachment.textpack")
		textPackTestWrite(t, name, textPackTestZip(t, map[string][]byte{
			"info.json":            []byte(`{"version":2,"type":"net.daringfireball.markdown"}`),
			"text.md":              []byte("![invalid](assets/payload.image)\n"),
			"assets/payload.image": []byte(payload),
		}))
		doc := bundleIntegrationRead(t, app, name)
		if got, err := app.ReadImageData("assets/payload.image", doc.Directory); err == nil || got != "" {
			t.Fatalf("fallback accepted non-image attachment: %q, %v", got, err)
		}
	}
}

func TestBundleImageCompatibilityFallbackDoesNotChangeOrdinaryMarkdownReads(t *testing.T) {
	app := bundleIntegrationApp(t)
	dir := textPackTestDirectory(t)
	for name, data := range map[string][]byte{
		"png.txt": textPackTestPNG(t),
		"svg":     []byte(`<svg xmlns="http://www.w3.org/2000/svg" width="1" height="1"/>`),
	} {
		textPackTestWrite(t, filepath.Join(dir, name), data)
		if _, err := app.ReadImageData(name, dir); err == nil {
			t.Fatalf("package-only fallback changed ordinary Markdown read policy for %s", name)
		}
	}
}

func TestBundleImageCompatibilitySVGCompletenessWarningIsPreserved(t *testing.T) {
	files := map[string][]byte{
		"info.json":            []byte(`{"version":2,"type":"net.daringfireball.markdown"}`),
		"text.md":              []byte("![svg](assets/drawing.image)\n"),
		"assets/drawing.image": []byte(`<svg xmlns="http://www.w3.org/2000/svg" width="1" height="1"><image href="https://example.invalid/pixel.png"/></svg>`),
	}
	parsed, err := parseTextBundleFiles(files)
	if err != nil || len(parsed.Warnings) != 1 || parsed.Warnings[0].Code != "EXTERNAL_RESOURCES" {
		t.Fatalf("SVG preview compatibility falsely certified completeness: %+v, %v", parsed, err)
	}
}

func TestBundleImageCompatibilityOwnExportReopensWithoutFetchingNetworkImages(t *testing.T) {
	var requests atomic.Int32
	server := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		requests.Add(1)
		w.Header().Set("Content-Type", "image/png")
		_, _ = w.Write(textPackTestPNG(t))
	}))
	defer server.Close()
	app := bundleIntegrationApp(t)
	dir := textPackTestDirectory(t)
	source := filepath.Join(dir, "Original.md")
	png := textPackTestPNG(t)
	textPackTestWrite(t, filepath.Join(dir, "本地.png"), png)
	remote := server.URL + "/network.png"
	original := "# Original\n![local](%E6%9C%AC%E5%9C%B0.png)\n![online](" + remote + ")\n"
	textPackTestWrite(t, source, []byte(original))
	prepared := "# Original\n![local](assets/image-001.png)\n![online](" + remote + ")\n"
	plan := []TextPackImage{{Source: "%E6%9C%AC%E5%9C%B0.png", Target: "assets/image-001.png"}, {Source: remote, Target: "assets/network.png"}}
	archive, report, err := app.buildTextPack(source, prepared, plan)
	if err != nil || report.AssetCount != 1 || len(report.Warnings) != 1 || report.Warnings[0].Code != "UNSAFE_REFERENCE" {
		t.Fatalf("local/remote export plan disagreed: %+v, %v", report, err)
	}
	if _, err = editableTextPackSnapshot(filepath.Join(dir, "Built.textpack"), archive); err != nil {
		t.Fatalf("built package invalid: %v", err)
	}
	pack := filepath.Join(dir, "Exported.textpack")
	if _, err = app.exportTextPackTo(source, pack, prepared, plan); err != nil {
		t.Fatal(err)
	}
	doc := bundleIntegrationRead(t, app, pack)
	got, err := app.ReadImageData("assets/image-001.png", doc.Directory)
	if err != nil || got != "data:image/png;base64,"+base64.StdEncoding.EncodeToString(png) {
		t.Fatalf("own PNG export did not reopen: %v", err)
	}
	if doc.Content != prepared || !strings.Contains(doc.Content, remote) || requests.Load() != 0 {
		t.Fatalf("remote image downloaded or source rewritten: requests=%d", requests.Load())
	}
	if _, err = os.Stat(filepath.Join(doc.Directory, "assets", "network.png")); !os.IsNotExist(err) {
		t.Fatalf("network image unexpectedly bundled: %v", err)
	}
	if bytes, err := os.ReadFile(source); err != nil || string(bytes) != original {
		t.Fatalf("export changed original document: %v", err)
	}
}
