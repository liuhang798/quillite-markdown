// Match the standard SoloMD export layout (info.json, text.markdown and assets)
// without depending on a user document or performing any network requests.
func TestBundleImageCompatibilityStandardExportLayoutAndJSONReceipt(t *testing.T) {
	app := bundleIntegrationApp(t)
	png := textPackTestPNG(t)
	var jpg bytes.Buffer
	if err := jpeg.Encode(&jpg, image.NewRGBA(image.Rect(0, 0, 2, 2)), nil); err != nil {
		t.Fatal(err)
	}
	svg := []byte(`<svg xmlns="http://www.w3.org/2000/svg" width="2" height="2"><rect width="2" height="2" fill="green"/></svg>`)
	fixtures := []struct {
		name, mime string
		data       []byte
	}{
		{"normal.png", "image/png", png},
		{"UPPER.PNG", "image/png", png},
		{"space name.png", "image/png", png},
		{"中文图片.png", "image/png", png},
		{"literal%20name.png", "image/png", png},
		{"photo.jpg", "image/jpeg", jpg.Bytes()},
		{"drawing.svg", "image/svg+xml", svg},
	}
	files := map[string][]byte{
		"info.json":     []byte(`{"version":2,"type":"net.daringfireball.markdown","creatorIdentifier":"app.solomd","transient":false}`),
		"text.markdown": []byte("# TextPack with local pictures\n"),
	}
	for _, fixture := range fixtures {
		files["assets/"+fixture.name] = fixture.data
	}
	name := filepath.Join(textPackTestDirectory(t), "Solo-layout.textpack")
	textPackTestWrite(t, name, textPackTestZip(t, files))
	doc := bundleIntegrationRead(t, app, name)
	encoded, err := json.Marshal(doc)
	if err != nil {
		t.Fatal(err)
	}
	var frontend Document
	if err = json.Unmarshal(encoded, &frontend); err != nil {
		t.Fatal(err)
	}
	if frontend.Path != name || frontend.BundleSessionID != doc.BundleSessionID || frontend.ResourcePath != doc.ResourcePath || frontend.Directory != filepath.Dir(frontend.ResourcePath) {
		t.Fatalf("JSON receipt lost package resource identity: %s", encoded)
	}
	for _, fixture := range fixtures {
		t.Run(fixture.name, func(t *testing.T) {
			reference := "assets/" + url.PathEscape(fixture.name)
			got, err := app.ReadImageData(reference, frontend.Directory)
			want := "data:" + fixture.mime + ";base64," + base64.StdEncoding.EncodeToString(fixture.data)
			if err != nil || got != want {
				t.Fatalf("standard packaged picture unavailable: %v, mime %q", err, strings.SplitN(got, ";", 2)[0])
			}
		})
	}
}

// TextBundle attachment filenames are not required to carry an image suffix.
// The package parser already verifies image bytes, so preview should agree.
func TestBundleImageCompatibilityVerifiedImageBytesWithoutExpectedSuffix(t *testing.T) {
	fixtures := []struct {
		name, mime string
		data       []byte
	}{
		{"png.bin", "image/png", textPackTestPNG(t)},
		{"png.dat", "image/png", textPackTestPNG(t)},
		{"png.txt", "image/png", textPackTestPNG(t)},
		{"png", "image/png", textPackTestPNG(t)},
		{"svg.image", "image/svg+xml", []byte(`<svg xmlns="http://www.w3.org/2000/svg" width="2" height="2"><rect width="2" height="2" fill="green"/></svg>`)},
		{"svg", "image/svg+xml", []byte(`<svg xmlns="http://www.w3.org/2000/svg" width="2" height="2"><rect width="2" height="2" fill="green"/></svg>`)},
	}
	for _, fixture := range fixtures {
		t.Run(fixture.name, func(t *testing.T) {
			app := bundleIntegrationApp(t)
			files := map[string][]byte{
				"info.json":              []byte(`{"version":2,"type":"net.daringfireball.markdown"}`),
				"text.md":                []byte("![image](assets/" + fixture.name + ")\n"),
				"assets/" + fixture.name: fixture.data,
			}
			parsed, err := parseTextBundleFiles(files)
			if err != nil || !bytes.Equal(parsed.Assets["assets/"+fixture.name], fixture.data) {
				t.Fatalf("actual image bytes not accepted by package parser: %v", err)
			}
			name := filepath.Join(textPackTestDirectory(t), "Local-image.textpack")
			textPackTestWrite(t, name, textPackTestZip(t, files))
			doc := bundleIntegrationRead(t, app, name)
			got, err := app.ReadImageData("assets/"+fixture.name, doc.Directory)
			want := "data:" + fixture.mime + ";base64," + base64.StdEncoding.EncodeToString(fixture.data)
			if err != nil || got != want {
				t.Fatalf("package parser accepted verified image but preview rejected it: %v, mime %q", err, strings.SplitN(got, ";", 2)[0])
			}
		})
	}
}

